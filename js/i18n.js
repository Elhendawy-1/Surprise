function t(key, lang, vars) {
  const table = I18N[lang] || I18N.en;
  let s = table[key];
  if (s === undefined) s = I18N.en[key] || '';
  if (vars) {
    Object.keys(vars).forEach(k => {
      s = s.split('{' + k + '}').join(vars[k]);
    });
  }
  return s;
}

window.I18N = I18N;
window.t = t;
